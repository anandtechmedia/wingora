import { palette, semanticColors, statusColors } from './colors.ts';
import { componentVariables } from './components.ts';
import { breakpoints, layout, motion, radius, shadow, spacingUnit, zIndex } from './foundations.ts';
import { fontFamily, fontSize, letterSpacing } from './typography.ts';

/**
 * Renders the tokens as a Tailwind CSS v4 `@theme` block plus plain custom properties.
 * Default Tailwind colours, shadows, radii, type sizes, breakpoints and containers are cleared,
 * so only Wingora tokens can be used in class names.
 */
export function toThemeCss(): string {
  const theme: string[] = [
    '--color-*: initial;', '--shadow-*: initial;', '--radius-*: initial;', '--text-*: initial;',
    '--breakpoint-*: initial;', '--container-*: initial;',
    `--spacing: ${spacingUnit};`,
    `--font-sans: ${fontFamily.sans};`, `--font-mono: ${fontFamily.mono};`,
    `--color-white: ${palette.white};`,
  ];

  for (const name of ['neutral', 'navy', 'indigo'] as const) {
    for (const [step, value] of Object.entries(palette[name])) theme.push(`--color-${name}-${step}: ${value};`);
  }
  for (const [name, value] of Object.entries(semanticColors)) theme.push(`--color-${name}: ${value};`);
  for (const [tone, values] of Object.entries(statusColors)) {
    for (const [variant, value] of Object.entries(values)) theme.push(`--color-${tone}-${variant}: ${value};`);
  }
  for (const [name, { size, lineHeight }] of Object.entries(fontSize)) {
    theme.push(`--text-${name}: ${size};`, `--text-${name}--line-height: ${lineHeight};`);
  }
  for (const [name, value] of Object.entries(letterSpacing)) theme.push(`--tracking-${name}: ${value};`);
  for (const [name, value] of Object.entries(radius)) theme.push(`--radius-${name}: ${value};`);
  for (const [name, value] of Object.entries(shadow)) theme.push(`--shadow-${name}: ${value};`);
  for (const [name, value] of Object.entries(breakpoints)) theme.push(`--breakpoint-${name}: ${value};`);
  for (const [name, value] of Object.entries(layout)) theme.push(`--container-${name}: ${value};`);
  theme.push(`--ease-standard: ${motion.easing.standard};`, `--ease-exit: ${motion.easing.exit};`);

  const root: string[] = [
    ...Object.entries(componentVariables()).map(([k, v]) => `${k}: ${v};`),
    ...Object.entries(zIndex).map(([k, v]) => `--z-${k}: ${v};`),
    ...Object.entries(motion.duration).map(([k, v]) => `--duration-${k}: ${v};`),
  ];

  return [
    '/* Generated by @wingora/design-tokens (pnpm tokens). Do not edit by hand. */',
    '@theme {',
    ...theme.map((line) => `  ${line}`),
    '}',
    '',
    ':root {',
    ...root.map((line) => `  ${line}`),
    '}',
    '',
  ].join('\n');
}
